import { mkdirSync, writeFileSync } from 'node:fs';
import { generateCanonicalFootballerProfile } from '../src/core/footballerWorld';
import { generateDevelopmentProfile } from '../src/core/playerCreator';
import { PLAYER_POSITIONS, getPlayerOverall } from '../src/core/playerOverall';
import { RandomGenerator } from '../src/core/random/RandomGenerator';
import {
  projectNpcAttributesAtDate,
  deriveNpcDevelopmentCurveId,
} from '../src/core/seasonDevelopment';
import { getAttributeFamily } from '../src/core/attributePresentation';
import type { DevelopmentFamily, PlayerAttributes, WorldFootballer } from '../src/types/domain';

const distribution = (values: number[]) => {
  const mean = values.reduce((sum, value) => sum + value, 0) / values.length;
  return {
    min: Math.min(...values),
    max: Math.max(...values),
    mean,
    standardDeviation: Math.sqrt(
      values.reduce((sum, value) => sum + (value - mean) ** 2, 0) / values.length,
    ),
  };
};
const families: DevelopmentFamily[] = ['technical', 'mental', 'physical', 'goalkeeper'];
const positions = PLAYER_POSITIONS.map((position) => {
  const cohort: WorldFootballer[] = Array.from({ length: 80 }, (_, index) => {
    const id = `pr167-diversity-${position}-${index}`;
    const footballer: WorldFootballer = {
      profile: generateCanonicalFootballerProfile({
        id,
        seed: 'pr167-diversity',
        age: 18,
        targetOverall: 58,
        primaryPosition: position,
      }),
      developmentProfile: generateDevelopmentProfile(RandomGenerator.fromSeed(`${id}:development`)),
      careerStatus: 'active',
    };
    footballer.developmentCurveId = deriveNpcDevelopmentCurveId(footballer);
    return footballer;
  });
  const at = (years: number) =>
    cohort.map((base) => ({
      ...base.profile,
      attributes: projectNpcAttributesAtDate({ footballer: base, date: `${2026 + years}-07-01` }),
    }));
  const profile = (player: (typeof cohort)[number]['profile']) => ({
    id: player.id,
    overall: getPlayerOverall(player, position),
    pace: player.attributes.pace,
    strength: player.attributes.strength,
    technique: player.attributes.technique,
    passing: player.attributes.passing,
    tackling: player.attributes.tackling,
    heading: player.attributes.heading,
    reading: player.attributes.gameReading,
    handling: player.attributes.handling,
    kicking: player.attributes.goalkeeperKicking,
  });
  const ranked = [...cohort].sort((a, b) =>
    position === 'goalkeeper'
      ? a.profile.attributes.handling -
        a.profile.attributes.goalkeeperKicking -
        (b.profile.attributes.handling - b.profile.attributes.goalkeeperKicking)
      : a.profile.attributes.pace -
        a.profile.attributes.technique -
        (b.profile.attributes.pace - b.profile.attributes.technique),
  );
  return {
    position,
    cohortSize: cohort.length,
    ages: [0, 10, 20].map((years) => {
      const players = at(years);
      return {
        age: 18 + years,
        overall: distribution(players.map((p) => getPlayerOverall(p, position))),
        families: families.map((family) => ({
          family,
          ...distribution(
            players.map((p) => {
              const keys = (Object.keys(p.attributes) as (keyof PlayerAttributes)[]).filter(
                (key) => getAttributeFamily(key) === family,
              );
              return keys.reduce((sum, key) => sum + p.attributes[key], 0) / keys.length;
            }),
          ),
        })),
        paceMinusTechnique: distribution(
          players.map((p) => p.attributes.pace - p.attributes.technique),
        ),
        handlingMinusKicking: distribution(
          players.map((p) => p.attributes.handling - p.attributes.goalkeeperKicking),
        ),
      };
    }),
    examples: [profile(ranked[0]!.profile), profile(ranked.at(-1)!.profile)],
  };
});
mkdirSync('docs/performance', { recursive: true });
writeFileSync(
  'docs/performance/PR167-diversity.json',
  JSON.stringify(
    {
      source:
        '640 profiles generated by the existing canonical archetype generator; all initially age 18 / target positional OVR 58. Immutable cohort, projected ten and twenty years later with its actual distinct development profiles. This is a controlled cohort, not a fixed population target.',
      seed: 'pr167-diversity',
      positions,
    },
    null,
    2,
  ) + '\n',
);
