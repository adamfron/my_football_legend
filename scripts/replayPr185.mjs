import { createHash } from 'node:crypto';
import { Buffer } from 'node:buffer';
import { readFileSync, writeFileSync } from 'node:fs';
import { gunzipSync } from 'node:zlib';
import console from 'node:console';
import { runFootballSkillTrial } from '../src/core/matchSimulation/footballPerformanceLab.ts';
import {
  runFootContactTrial,
  runFeintTrial,
  runJumpTrial,
  runHoopTrial,
  runRepeatedSprintTrial,
  runPhysicalContest,
  runGoalkeeperTrial,
} from '../src/core/matchSimulation/extendedPhysicalLab.ts';

const sha = (v) =>
  createHash('sha256')
    .update(Buffer.isBuffer(v) ? v : JSON.stringify(v))
    .digest('hex');
const read = (name) => JSON.parse(readFileSync(`docs/performance/PR185-${name}.json`, 'utf8'));
const dispatch = [
  ['foot-contact-techniques', (i) => runFootContactTrial(i.config, i.player, i.seed)],
  ['elastico-feint', (i) => runFeintTrial(i.config, i.player, i.seed)],
  ['jumping-and-heading', (i) => runJumpTrial(i.config, i.player, i.seed)],
  ['hoop-trajectories', (i) => runHoopTrial(i)],
  ['repeated-sprints', (i) => runRepeatedSprintTrial(i.config, i.player, i.seed)],
  [
    'contact-and-shielding',
    (i) => runPhysicalContest(i.state, i.defenderId, i.carrierId, i.technique),
  ],
  ['goalkeeper-distribution', (i) => runGoalkeeperTrial(i.config, i.player, i.seed)],
  ['autonomous-experiments', (i, r) => runFootballSkillTrial(i.config, i.player, r.seed)],
];
const rows = [];
for (const [group, run] of dispatch) {
  const receipt = read(group),
    bytes = readFileSync(receipt.archive);
  if (sha(bytes) !== receipt.archiveSha256) throw Error(`Archive changed: ${group}`);
  const trials = JSON.parse(gunzipSync(bytes));
  // Keep this a small replay audit; the complete matrix is regenerated by benchmarkPr185.mjs.
  const trial = trials[0],
    expected = receipt.rows[0];
  if (sha(trial.input) !== expected.inputSha256 || sha(trial.result) !== expected.resultSha256)
    throw Error(`Stored trial fingerprint mismatch: ${group}`);
  const actual = run(trial.input, trial.result);
  const actualSha256 = sha(actual);
  if (actualSha256 !== expected.resultSha256) throw Error(`Replay mismatch: ${group}`);
  rows.push({
    group,
    id: trial.id,
    expectedSha256: expected.resultSha256,
    actualSha256,
    equal: true,
  });
}
writeFileSync(
  'docs/performance/PR185-replay.json',
  JSON.stringify({
    sourceSha256: read('performance').sourceSha256,
    method:
      'Fresh process, archived complete input, exact complete result equality; eight representative protocols, not a second independent sample.',
    rows,
  }) + '\n',
);
console.log(JSON.stringify({ replayed: rows.length, allEqual: true }));
